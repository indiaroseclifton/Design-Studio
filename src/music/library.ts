const slug = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
export const SONGS: Song[] = R.map(([title, artist, year, bpm, energy, genres, moments]) => ({
  id: slug(title + '-' + artist),
  title,
  artist,
  year,
  bpm,
  energy,
  genres: genres.split(',') as Genre[],
  moments,
}));
export const SONG_BY_ID = new Map(SONGS.map((s) => [s.id, s]));
